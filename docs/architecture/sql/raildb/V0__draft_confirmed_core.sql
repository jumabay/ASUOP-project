-- History: partition by month on dislocation_ts (axis = GETTING_DATE equivalent until DT1 closes).
-- P3C-0: technical PK only; retain duplicate source rows; no UK(kit,wagon).
CREATE TABLE rail_disl_event (
    event_id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    kit_id              NUMBER(19),              -- nullable if KIT_FK orphan
    wagon_id            NUMBER(19) NOT NULL,
    wagon_code          VARCHAR2(32) NOT NULL,
    station_code        VARCHAR2(16),
    train_index         VARCHAR2(64),
    -- Partition key: TIMESTAMP (no TZ) for 12.2 RANGE stability; store UTC wall-clock. TZ policy = R1-Q-TZ.
    dislocation_ts      TIMESTAMP NOT NULL,       -- getting_ts equivalent
    location_ts         TIMESTAMP,               -- LOCATION_DATE attr (DT1)
    operation_code      VARCHAR2(32),
    dest_station_code   VARCHAR2(16),
    depart_station_code VARCHAR2(16),
    receiver_code       VARCHAR2(64),
    sender_code         VARCHAR2(64),
    wagon_type          VARCHAR2(64),
    wagon_owner         NUMBER(10),
    nod_code            VARCHAR2(64),
    weight_state        VARCHAR2(32),
    work_state          VARCHAR2(32),
    doc_number          VARCHAR2(64),
    cargo_code          VARCHAR2(32),
    cargo_weight        VARCHAR2(32),
    capacity            VARCHAR2(32),
    message_code        VARCHAR2(32),
    operation_ts        TIMESTAMP WITH TIME ZONE,
    containers          VARCHAR2(4000),
    source_system       VARCHAR2(16) NOT NULL,
    provenance_key      VARCHAR2(128) NOT NULL,  -- reportId:wagonId:ordinal (batch idempotency)
    source_ordinal      NUMBER(10) DEFAULT 0 NOT NULL,
    content_hash        VARCHAR2(64),            -- detect only; never delete by hash
    legacy_report_id    NUMBER(19),
    legacy_wagon_id     NUMBER(19),
    CONSTRAINT pk_rail_disl_event PRIMARY KEY (event_id, dislocation_ts),
    CONSTRAINT fk_rail_disl_wagon FOREIGN KEY (wagon_id) REFERENCES rail_wagon (wagon_id),
    CONSTRAINT fk_rail_disl_kit FOREIGN KEY (kit_id) REFERENCES rail_import_kit (kit_id)
)
PARTITION BY RANGE (dislocation_ts) (
    PARTITION p_min VALUES LESS THAN (TIMESTAMP '2025-01-01 00:00:00'),
    PARTITION p_2025_11 VALUES LESS THAN (TIMESTAMP '2025-12-01 00:00:00'),
    PARTITION p_max VALUES LESS THAN (MAXVALUE)
);

-- P3C-0: do NOT add UNIQUE(kit_id, wagon_id) — DBTC has no UK; duplicates retained.
