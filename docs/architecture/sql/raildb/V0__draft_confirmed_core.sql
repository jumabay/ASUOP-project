CREATE TABLE rail_wagon_current (
    wagon_id            NUMBER(19) PRIMARY KEY,
    station_id          NUMBER(19),
    station_code        VARCHAR2(16),
    operation_code      VARCHAR2(32),
    dislocation_ts      TIMESTAMP WITH TIME ZONE,
    train_index         VARCHAR2(64),
    updated_at_utc      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_rail_current_wagon FOREIGN KEY (wagon_id) REFERENCES rail_wagon (wagon_id)
);

CREATE TABLE rail_intake_event (
    intake_id           NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_type         VARCHAR2(16) NOT NULL,
    idempotency_key     VARCHAR2(128) NOT NULL,
    request_summary     VARCHAR2(1000),
    payload_sha256      VARCHAR2(64),
    status_code         VARCHAR2(32) NOT NULL,
    received_at_utc     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_rail_intake_idem UNIQUE (idempotency_key)
);

CREATE TABLE rail_import_kit (
    kit_id              NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    intake_id           NUMBER(19),
    file_name           VARCHAR2(260) NOT NULL,
    kit_type            NUMBER(3) NOT NULL,
    channel_code        VARCHAR2(32) NOT NULL,
    hour_slot           TIMESTAMP NOT NULL,
    line_count          NUMBER(10) DEFAULT 0 NOT NULL,
    status_code         VARCHAR2(32) NOT NULL,
    registered_at_utc   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_rail_kit_file_type UNIQUE (file_name, kit_type),
    CONSTRAINT fk_rail_kit_intake FOREIGN KEY (intake_id) REFERENCES rail_intake_event (intake_id)
);

CREATE INDEX ix_rail_kit_channel_hour ON rail_import_kit (channel_code, hour_slot);

-- History: partition by month on dislocation_ts (PROVISIONAL axis = getting_date equivalent)
CREATE TABLE rail_disl_event (
    event_id            NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
    kit_id              NUMBER(19),
    wagon_id            NUMBER(19) NOT NULL,
    wagon_code          VARCHAR2(32) NOT NULL,
    station_code        VARCHAR2(16),
    train_index         VARCHAR2(64),
    -- Partition key: TIMESTAMP (no TZ) for 12.2 RANGE stability; store UTC wall-clock. TZ policy = R1-Q-TZ / P3B.
    dislocation_ts      TIMESTAMP NOT NULL,
    operation_code      VARCHAR2(32),
    dest_station_code   VARCHAR2(16),
    depart_station_code VARCHAR2(16),
    receiver_code       VARCHAR2(64),
    sender_code         VARCHAR2(64),
    wagon_type          VARCHAR2(64),
    wagon_owner         NUMBER(10),
    nod_code            VARCHAR2(64),
    weight_state        VARCHAR2(32),
    work_state          VARCHAR2(32),
    doc_number          VARCHAR2(64),
    cargo_code          VARCHAR2(32),
    cargo_weight        VARCHAR2(32),
    capacity            VARCHAR2(32),
    message_code        VARCHAR2(32),
    operation_ts        TIMESTAMP WITH TIME ZONE,
    containers          VARCHAR2(4000),
    source_system       VARCHAR2(16) NOT NULL,
    event_key           VARCHAR2(512),
    content_hash        VARCHAR2(64),
    legacy_report_id    NUMBER(19),
    CONSTRAINT pk_rail_disl_event PRIMARY KEY (event_id, dislocation_ts),
    CONSTRAINT fk_rail_disl_wagon FOREIGN KEY (wagon_id) REFERENCES rail_wagon (wagon_id),
    CONSTRAINT fk_rail_disl_kit FOREIGN KEY (kit_id) REFERENCES rail_import_kit (kit_id)
)
PARTITION BY RANGE (dislocation_ts) (
    PARTITION p_min VALUES LESS THAN (TIMESTAMP '2025-01-01 00:00:00'),
    PARTITION p_2025_11 VALUES LESS THAN (TIMESTAMP '2025-12-01 00:00:00'),
    PARTITION p_max VALUES LESS THAN (MAXVALUE)
);

