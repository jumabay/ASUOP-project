-- References
CREATE TABLE rail_station (
    station_id      NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code    VARCHAR2(16) NOT NULL,
    station_name    VARCHAR2(256),
    legacy_id       NUMBER(19),
    CONSTRAINT uk_rail_station_code UNIQUE (station_code)
);

CREATE TABLE rail_wagon (
    wagon_id        NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wagon_code      VARCHAR2(32) NOT NULL,
    model_code      VARCHAR2(64),
    wagon_kind      VARCHAR2(64),
    owner_name      VARCHAR2(256),
    home_station_id NUMBER(19),
    inventory_park  CHAR(1) DEFAULT 'N' NOT NULL,
    legacy_wagon_id NUMBER(19),
    CONSTRAINT uk_rail_wagon_code UNIQUE (wagon_code),
    CONSTRAINT fk_rail_wagon_home FOREIGN KEY (home_station_id) REFERENCES rail_station (station_id)
);

